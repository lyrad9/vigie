// Signs the hero video's Mux playback tokens with the signing key in .env.local, and writes them
// to src/lib/video-tokens.ts. Only the tokens are committed: each one plays this one video and
// expires (2 years by default). The private key never leaves this machine.
//
//   node scripts/mux-tokens.mjs            # regenerate before the old tokens expire
//   node scripts/mux-tokens.mjs --check    # also fetch the stream with the new token
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const YEARS = 2;

function readEnv(file) {
  const env = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) env[m[1]] = m[2];
  }
  return env;
}

const env = { ...readEnv(path.join(ROOT, ".env.local")), ...process.env };
const keyId = env.MUX_SIGNING_KEY_ID;
const keyB64 = env.MUX_SIGNING_KEY_PRIVATE;
if (!keyId || !keyB64) {
  console.error("MUX_SIGNING_KEY_ID and MUX_SIGNING_KEY_PRIVATE are missing from website/.env.local");
  process.exit(1);
}
const privateKey = Buffer.from(keyB64, "base64").toString("utf8");

const site = fs.readFileSync(path.join(ROOT, "src/lib/site.ts"), "utf8");
const playbackId = site.match(/playbackId:\s*"([^"]+)"/)?.[1];
if (!playbackId) {
  console.error("No video.playbackId in src/lib/site.ts");
  process.exit(1);
}

const b64url = (data) => Buffer.from(typeof data === "string" ? data : JSON.stringify(data)).toString("base64url");
const exp = Math.floor(Date.now() / 1000) + YEARS * 365 * 24 * 3600;

/** aud: v = video, t = thumbnail, s = storyboard (Mux signed URLs). */
function sign(aud) {
  const head = b64url({ alg: "RS256", typ: "JWT", kid: keyId });
  const body = b64url({ sub: playbackId, aud, exp, kid: keyId });
  const signature = crypto.sign("RSA-SHA256", Buffer.from(`${head}.${body}`), privateKey).toString("base64url");
  return `${head}.${body}.${signature}`;
}

const tokens = { playback: sign("v"), thumbnail: sign("t"), storyboard: sign("s") };
const expires = new Date(exp * 1000).toISOString().slice(0, 10);
fs.writeFileSync(
  path.join(ROOT, "src/lib/video-tokens.ts"),
  `// Generated by scripts/mux-tokens.mjs: signed playback tokens for the hero video, valid until ${expires}.\n` +
    `// Public by design (each plays this one video); the signing key stays in .env.local.\n` +
    `export const videoTokens = ${JSON.stringify(tokens, null, 2)};\n` +
    `export const videoTokensExpire = "${expires}";\n`,
);
console.log(`tokens written for ${playbackId}, valid until ${expires}`);

if (process.argv.includes("--check")) {
  const res = await fetch(`https://stream.mux.com/${playbackId}.m3u8?token=${tokens.playback}`);
  const thumb = await fetch(`https://image.mux.com/${playbackId}/thumbnail.webp?token=${tokens.thumbnail}`);
  console.log(`stream: ${res.status} · thumbnail: ${thumb.status}`);
  if (res.ok) console.log((await res.text()).split("\n").filter((l) => l.startsWith("#EXT-X-STREAM-INF")).join("\n"));
  if (!res.ok || !thumb.ok) process.exit(1);
}
