/** 'en' or 'fr' for a setting of 'auto' | 'en' | 'fr' and the system locale. */
export function resolveLanguage(setting, locale = '') {
  if (setting === 'en' || setting === 'fr') return setting;
  return String(locale).toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  const t = (key, vars = {}) => {
    const text = table[key] ?? STRINGS.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
  t.plural = (key, n, vars = {}) => t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...vars });
  return t;
}
